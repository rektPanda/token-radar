// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols only. A protocol is pre-token when its record carries no token
// (no market cap, no CoinGecko id, no symbol). Protocols whose token already trades are kept apart in
// the Live view, shown at the market's own value, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, the same function for every row:
//
//   growth     = clamp(change_7d, -60, 120) per cent, 0 when unreported
//   growthMult = 1 + (growth / 100) x 0.8
//   maturity   = 0.5 + 0.5 x min(age_days, 1460) / 1460   (age unknown: 365 days)
//   breadth    = 1 + 0.05 x min(chains, 5)                (more chains, wider distribution)
//   category   = 0.9 + 0.2 x (category TVL / largest category TVL in the snapshot)
//   implied    = round(tvl_usd x 0.25 x growthMult x maturity x breadth x category)
//
// TVL is the anchor: a protocol's locked value is the closest thing to a balance sheet a pre-token
// protocol has. Growth rewards momentum and punishes shrinkage. Maturity rewards survival: a protocol
// that has run for years with no token has had longer to earn one. Breadth rewards multi-chain reach.
// The category factor is computed from the snapshot itself (each category's share of total TVL), so no
// category is favoured by hand. No protocol name is ever special-cased.
//
// The board covers the whole watchlist (the floor, never the ceiling) plus every other protocol that
// passes the watchlist's own eligibility rule: pre-token, not an exchange, not a versioned pool, not a
// wrapped, staked or bridged product of a token that already trades.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

